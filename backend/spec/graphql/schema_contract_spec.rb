require "rails_helper"
require "rake"

# The frontend validates its queries against this committed SDL; this spec keeps it in step with the
# live schema, so a breaking change shows up as a failing test on BOTH sides.
RSpec.describe "GraphQL schema contract" do
  it "matches frontend/src/graphql/schema.graphql (regenerate with `bin/rails graphql:dump_schema`)" do
    committed = Rails.root.join("../frontend/src/graphql/schema.graphql")

    expect(committed.read).to eq(SalaryInsightsSchema.to_definition)
  end

  it "is regenerated by `bin/rails graphql:dump_schema`" do
    Rails.application.load_tasks if Rake::Task.tasks.none? { |t| t.name == "graphql:dump_schema" }
    target = Pathname(Dir.mktmpdir).join("schema.graphql")
    ENV["SCHEMA_PATH"] = target.to_s

    expect { Rake::Task["graphql:dump_schema"].tap(&:reenable).invoke }.to output(/Wrote #{target}/).to_stdout
    expect(target.read).to eq(SalaryInsightsSchema.to_definition)
  ensure
    ENV.delete("SCHEMA_PATH")
  end
end
